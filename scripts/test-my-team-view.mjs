import assert from "node:assert/strict";
import vm from "node:vm";
import { readFileSync } from "node:fs";
import { renderMyTeamParticipant, renderMyTeamCampaignSummary, renderMyTeamAchievements } from "../js/my-team-view.js";
import { buildMyTeamAchievements, buildMyTeamMoment } from "../js/my-team-moments.js";
import { renderMyTeamNumberCard } from "../js/my-team-statistics.js";

const context={row:{position:8,points:40,goalDifference:2,playedGames:30,won:11,draw:7,lost:12,goalsFor:35,goalsAgainst:33},stats:{games:8,points:23,hits:5,exact:1},profile:{icon:"🧠",name:"O Estratégico",text:"Resultados avaliados."},synergy:62,confidence:75,recent:[],next:null};
context.moment=buildMyTeamMoment({games:8,points:23,hits:5,confidence:75});
context.achievements=buildMyTeamAchievements({games:8,exact:1,accuracy:62,bestSequence:2});
const html=renderMyTeamParticipant(context,"Clube","Boa leitura");
assert.equal((html.match(/home-mini-card club-stat/g)||[]).length,5);
assert.equal((html.match(/aria-label="Resultados certos"/g)||[]).length,1);
assert.match(html,/63% dos jogos/);
assert.match(html,/8 palpites concluídos com o clube/);
assert.doesNotMatch(html,/my-team-moment-card|my-team-moment-indicators|leitura correta|Jogos analisados/);
assert.equal((html.match(/Perfil e Sintonia/g)||[]).length,1);
assert.match(html,/Palpites de vitória/);
const featured=renderMyTeamParticipant({...context,moment:buildMyTeamMoment({games:8,hits:5,latestExact:true})},"Clube","Boa leitura");
assert.equal((featured.match(/my-team-moment-inline/g)||[]).length,1);
assert.doesNotMatch(featured,/my-team-moment-indicators/);
assert.match(renderMyTeamParticipant({...context,stats:{games:0,points:0,hits:0,exact:0}},"Clube","Em construção"),/de 0 possíveis/);
assert.doesNotMatch(renderMyTeamParticipant({...context,stats:{games:0,points:0,hits:0,exact:0}},"Clube","Em construção"),/NaN|Infinity|undefined|62<em/);
const campaign=renderMyTeamCampaignSummary(context.row);
assert.equal((campaign.match(/home-mini-card club-stat/g)||[]).length,6);
assert.match(campaign,/TEMPORADA COMPLETA/);
assert.doesNotMatch(campaign,/data-my-team-action|Pontos conquistados/);
assert.match(renderMyTeamCampaignSummary(null),/em atualização/);
assert.doesNotMatch(renderMyTeamAchievements(context.achievements),/details" open/);
assert.match(renderMyTeamAchievements(context.achievements,true),/details" open/);
assert.equal((renderMyTeamAchievements(context.achievements).match(/role="progressbar"/g)||[]).length,5);
assert.doesNotMatch(renderMyTeamNumberCard({label:'<script>',value:'<img>',unit:'<b>'}),/<script>|<img>|<b>/);

// Execute the real complete screen renderer, including its refreshed detail states.
const source=readFileSync(new URL("../js/app.js",import.meta.url),"utf8");
const start=source.indexOf("function renderMyTeam(){"),end=source.indexOf("let homeFavoriteExpanded=",start);
const host={innerHTML:"",querySelector:()=>({open:true})};
const scope={state:{participant:{time_favorito:"Clube"}},$:()=>host,findTeam:()=>({name:"Clube",key:"clube"}),favoriteTeamContext:()=>context,teamDisplayName:x=>String(x||""),escapeHtml:x=>String(x??""),initials:()=>"CL",normalizeTeamKey:x=>String(x||"").toLowerCase(),favoriteTeamResult:()=>"V",favoriteFormMarkup:()=>"",favoriteSynergyLabel:()=>"Boa leitura",renderMyTeamParticipant,renderMyTeamCampaignSummary,renderMyTeamAchievements,myTeamClubStatistics:()=>'<section class="club-statistics">Estatísticas por partida</section>'};
vm.createContext(scope);
vm.runInContext(source.slice(start,end),scope);
vm.runInContext("renderMyTeam()",scope);
assert.equal((host.innerHTML.match(/data-my-team-action="standings"/g)||[]).length,1);
assert.match(host.innerHTML,/Ver classificação/);
assert.match(host.innerHTML,/data-my-team-action="campaign"/);
assert.match(host.innerHTML,/data-my-team-action="games"/);
assert.ok(host.innerHTML.indexOf("myTeamPerformanceTitle")<host.innerHTML.indexOf("myTeamClubNumbersTitle"));
assert.ok(host.innerHTML.indexOf("club-statistics")<host.innerHTML.indexOf("my-team-achievements-details"));
assert.match(host.innerHTML,/details" open/);
scope.state.participant.time_favorito=null;scope.findTeam=()=>null;
vm.runInContext("renderMyTeam()",scope);
assert.match(host.innerHTML,/Escolha o seu time/);
console.log("Meu Time simplificado: dados do participante/clube separados, perfil unificado, momentos condicionais, conquistas preservadas e navegação aprovados.");
